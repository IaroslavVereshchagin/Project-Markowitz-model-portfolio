from imports import pd, requests


def get_moex_data(paper, day_start="2025-01-01"):
    link = f"https://moex.com{paper}.json"                            # Ссылка на историю торгов конкретной бумаги
    params = {"from": day_start, "columns": "TRADEDATE, CLOSE"}
  
    response = requests.get(link, params = params)                    # Скачиваем данные из интернета 
    raw_json = response.json()
    
    rows = raw_json["history"]["data"]                                # Достаем массив цен и дат
    table = pd.DataFrame(rows, columns = ["Date", "Close"])
  
    table.set_index("Date", inplace = True)                           # Ставим дату главным ориентиром в строке 
    return table["Close"]


